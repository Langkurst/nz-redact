// Checks on the web page and the repository itself. Run with:  npm test
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const html = read("index.html");

test("the page's security policy blocks every connection, so pasted text cannot leave", () => {
  const csp = (html.match(/http-equiv="Content-Security-Policy" content="([^"]+)"/) || [])[1] || "";
  assert.match(csp, /connect-src 'none'/);
  assert.match(csp, /form-action 'none'/);
  assert.match(csp, /default-src 'self'/);
  assert.match(csp, /script-src 'self'(;|$)/, "scripts only from this site, never inline");
  assert.ok(!/<script>[^<]/.test(html), "no inline scripts");
  assert.ok(!/ style="/.test(html), "no inline styles");
  assert.ok(!/on(click|load|error|input)=/i.test(html), "no inline event handlers");
});

test("every local file the page, manifest and offline list refer to exists", () => {
  const refs = [...html.matchAll(/(?:src|href)="([^"#]+?)(?:#[^"]*)?"/g)].map((m) => m[1]).filter((u) => !/^(https?:|mailto:|\.\/$)/.test(u));
  const manifest = JSON.parse(read("manifest.webmanifest"));
  manifest.icons.forEach((i) => refs.push(i.src));
  const sw = read("sw.js");
  const offline = JSON.parse(sw.match(/var FILES = (\[[\s\S]*?\]);/)[1].replace(/'/g, '"'));
  offline.filter((f) => f !== "./").forEach((f) => refs.push(f));
  for (const r of refs) assert.ok(fs.existsSync(path.join(ROOT, r)), r);
  assert.ok(offline.includes("src/nz-redact.js") && offline.includes("index.html"));
});

test("the offline copy and the library carry the same version", () => {
  const R = require("../src/nz-redact.js");
  assert.match(read("sw.js"), new RegExp(`"nz-redact-${R.version.replace(/\./g, "\\.")}"`));
  assert.equal(JSON.parse(read("package.json")).version, R.version);
});

test("labels: every form control has a name and every in-page link has a target", () => {
  for (const [, id] of html.matchAll(/<(?:textarea|input)[^>]*id="([^"]+)"/g)) {
    if (/type="file"/.test(html.match(new RegExp(`<input[^>]*id="${id}"[^>]*>`)) || "")) continue;
    assert.match(html, new RegExp(`for="${id}"`), id);
  }
  for (const [, id] of html.matchAll(/href="#([^"]+)"/g)) assert.match(html, new RegExp(`id="${id}"`), id);
  for (const [, id] of html.matchAll(/aria-(?:controls|labelledby)="([^"]+)"/g)) assert.match(html, new RegExp(`id="${id}"`), id);
});

// The public repository carries no tool or vendor branding.
const SKIP = new Set([".git", "node_modules", "fonts"]);
function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => SKIP.has(e.name) ? [] :
    e.isDirectory() ? files(path.join(dir, e.name)) : [path.join(dir, e.name)]);
}
test("no tool branding anywhere in the repository", () => {
  const banned = /claude|anthropic|co-authored-by|chatgpt wrote|ai agent|ai coding|generated by ai|copilot/i;
  for (const f of files(ROOT)) {
    if (/\.(png|woff2|ico)$/.test(f) || f.endsWith("site.test.js")) continue;
    const text = fs.readFileSync(f, "utf8");
    const m = text.match(banned);
    assert.equal(m, null, `${path.relative(ROOT, f)}: "${m && m[0]}"`);
  }
});
